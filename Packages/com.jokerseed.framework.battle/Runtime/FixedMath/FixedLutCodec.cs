using System;
using System.IO;
using System.Text;

namespace Framework.FixedMath
{
    /// <summary>
    /// 定点查找表（<c>SinLut</c> / <c>TanLut</c>）的无损文本编码：二阶差分 → ZigZag → LEB128 变长整数 → Base64。
    /// 差分用 unchecked 环绕运算，编码与解码互为逆运算，逐位一致；不使用 DeflateStream（IL2CPP / WebGL 上不可靠）。
    /// 表数据由 <c>tools/Framework.LutTools</c> 生成，<c>tests/Framework.Sim.Tests</c> 用 SHA-256 校验解码结果。
    /// </summary>
    internal static class FixedLutCodec
    {
        /// <summary>把 Base64 文本（可含空白换行）解码为查找表。</summary>
        /// <param name="data">编码文本。</param>
        /// <param name="count">表项数。</param>
        /// <returns>解码后的表。</returns>
        /// <exception cref="InvalidDataException">数据长度与 <paramref name="count"/> 不符。</exception>
        public static long[] Decode(string data, int count)
        {
            var compact = new StringBuilder(data.Length);
            for (var i = 0; i < data.Length; i++)
            {
                var c = data[i];
                if (c != ' ' && c != '\r' && c != '\n' && c != '\t')
                {
                    compact.Append(c);
                }
            }

            var bytes = Convert.FromBase64String(compact.ToString());
            var result = new long[count];
            var pos = 0;
            long value = 0;
            long delta = 0;
            for (var i = 0; i < count; i++)
            {
                var zigzag = ReadVarint(bytes, ref pos);
                var second = (long)(zigzag >> 1) ^ -(long)(zigzag & 1);
                unchecked
                {
                    delta += second;
                    value += delta;
                }

                result[i] = value;
            }

            if (pos != bytes.Length)
            {
                throw new InvalidDataException($"LUT data has {bytes.Length - pos} trailing bytes.");
            }

            return result;
        }

        /// <summary>把查找表编码为 Base64 文本（不含换行）。</summary>
        /// <param name="values">表数据。</param>
        /// <returns>编码文本。</returns>
        public static string Encode(long[] values)
        {
            using (var stream = new MemoryStream(values.Length * 2))
            {
                long previous = 0;
                long previousDelta = 0;
                for (var i = 0; i < values.Length; i++)
                {
                    long delta;
                    long second;
                    unchecked
                    {
                        delta = values[i] - previous;
                        second = delta - previousDelta;
                    }

                    WriteVarint(stream, (ulong)((second << 1) ^ (second >> 63)));
                    previous = values[i];
                    previousDelta = delta;
                }

                return Convert.ToBase64String(stream.ToArray());
            }
        }

        /// <summary>生成 <c>partial struct FP</c> 的查找表源码文件内容。</summary>
        /// <param name="fieldName">字段名，如 <c>SinLut</c>。</param>
        /// <param name="values">表数据。</param>
        /// <returns>C# 源码。</returns>
        public static string WriteSource(string fieldName, long[] values)
        {
            var encoded = Encode(values);
            var sb = new StringBuilder(encoded.Length + encoded.Length / 100 * 2 + 1024);
            sb.Append("// <auto-generated>\n");
            sb.Append("// 由 tools/Framework.LutTools 生成，请勿手改。编码格式见 FixedLutCodec。\n");
            sb.Append("// </auto-generated>\n");
            sb.Append("namespace Framework.FixedMath\n{\n    partial struct FP\n    {\n");
            sb.Append("        const int ").Append(fieldName).Append("Count = ").Append(values.Length).Append(";\n\n");
            sb.Append("        const string ").Append(fieldName).Append("Data = @\"\n");
            for (var i = 0; i < encoded.Length; i += 100)
            {
                sb.Append(encoded, i, Math.Min(100, encoded.Length - i)).Append('\n');
            }

            sb.Append("\";\n\n");
            sb.Append("        /// <summary>查找表（Q31.32 原始值）。</summary>\n");
            sb.Append("        public static readonly long[] ").Append(fieldName)
                .Append(" = FixedLutCodec.Decode(").Append(fieldName).Append("Data, ").Append(fieldName).Append("Count);\n");
            sb.Append("    }\n}\n");
            return sb.ToString();
        }

        static ulong ReadVarint(byte[] bytes, ref int pos)
        {
            ulong result = 0;
            var shift = 0;
            while (true)
            {
                if (pos >= bytes.Length)
                {
                    throw new InvalidDataException("LUT data truncated.");
                }

                var b = bytes[pos++];
                result |= (ulong)(b & 0x7F) << shift;
                if ((b & 0x80) == 0)
                {
                    return result;
                }

                shift += 7;
            }
        }

        static void WriteVarint(Stream stream, ulong value)
        {
            while (value >= 0x80)
            {
                stream.WriteByte((byte)(value | 0x80));
                value >>= 7;
            }

            stream.WriteByte((byte)value);
        }
    }
}
